#!/usr/bin/env node
// Regenerates packages/sdk/src/abis from Foundry artifacts. Run after `forge build`.
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const outDir = join(root, "packages/sdk/src/abis");
const contracts = [
  ["IndexVault", "IndexVault.sol"],
  ["IndexFactory", "IndexFactory.sol"],
  ["IndexLens", "IndexLens.sol"],
  ["AdapterRegistry", "AdapterRegistry.sol"],
  ["AllowlistCompliance", "AllowlistCompliance.sol"],
  ["IStrategyAdapter", "IStrategyAdapter.sol"],
  // Testnet-only helpers (faucet token, yield-emulating ERC-4626). Used by the app on testnets.
  ["TestnetToken", "TestnetToken.sol"],
  ["TestnetYieldVault", "TestnetYieldVault.sol"],
];
mkdirSync(outDir, { recursive: true });
const names = [];
for (const [name, file] of contracts) {
  const artifact = JSON.parse(readFileSync(join(root, "out", file, `${name}.json`), "utf8"));
  const exportName = `${name[0].toLowerCase()}${name.slice(1)}Abi`;
  writeFileSync(
    join(outDir, `${name}.ts`),
    `// Generated by scripts/export-abis.mjs. Do not edit.\nexport const ${exportName} = ${JSON.stringify(artifact.abi, null, 2)} as const;\n`,
  );
  names.push([name, exportName]);
}
writeFileSync(
  join(outDir, "index.ts"),
  "// Generated by scripts/export-abis.mjs. Do not edit.\n" +
    names.map(([n, e]) => `export { ${e} } from "./${n}.js";`).join("\n") +
    "\n",
);
console.log(`Exported ${names.length} ABIs to ${outDir}`);
